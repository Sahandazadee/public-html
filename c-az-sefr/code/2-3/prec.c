#include <stdio.h>

int main(void)
{
    printf("2 + 3 * 4       = %d\n", 2 + 3 * 4);
    printf("(2 + 3) * 4     = %d\n", (2 + 3) * 4);
    printf("10 - 4 - 3      = %d\n", 10 - 4 - 3);
    printf("100 / 10 * 5    = %d\n", 100 / 10 * 5);
    printf("100 / (10 * 5)  = %d\n", 100 / (10 * 5));
    printf("-2 * 3 + 1      = %d\n", -2 * 3 + 1);
    return 0;
}
